import { _electron as electron } from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';

const output = path.resolve(`test-results/audit-${Date.now()}`);
const profile = path.join(output, 'profile');
await fs.mkdir(path.join(profile, 'videos', '.pending'), { recursive: true });
await fs.writeFile(path.join(profile, 'videos', '.pending', 'recovered.webm'), Buffer.from([1, 2, 3, 4]));
const env = { ...process.env, LOCAL_RECORDER_TEST_DIR: profile, LOCAL_RECORDER_PACKAGED_TEST: '1' };
delete env.ELECTRON_RUN_AS_NODE;
let app;
try {
  app = await electron.launch({ args: ['.'], env, chromiumSandbox: true });
  const page = await app.firstWindow();
  page.setDefaultTimeout(20000);
  await page.getByRole('button', { name: 'Biblioteca', exact: true }).click();
  await page.getByText('1 grabación recuperada', { exact: true }).waitFor();
  await page.getByText('Recuperada', { exact: true }).waitFor();
  console.log('PASS recovered recording is visible and actionable');

  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().find(window => window.getTitle() === 'Tomixel')?.webContents.send('navigate', 'repeat-tutorial'));
  await page.getByRole('dialog', { name: 'Aprende lo esencial en cinco pasos' }).waitFor();
  await page.getByRole('button', { name: 'Ver recorrido', exact: true }).click();
  assert.equal(await page.getByText('Paso 1 de 5', { exact: true }).isVisible(), true);
  const spotlight = await page.locator('.tour-focus').evaluate(element => ({ background: getComputedStyle(element).backgroundColor, shadow: getComputedStyle(element).boxShadow }));
  assert.match(spotlight.background, /rgba\(0, 0, 0, 0\)/); assert.match(spotlight.shadow, /9999px/);
  await page.screenshot({ path: path.join(output, 'tutorial-spotlight.png') });
  await page.getByRole('button', { name: 'Siguiente', exact: true }).click(); await page.getByText('Paso 2 de 5', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Siguiente', exact: true }).click(); await page.getByText('Paso 3 de 5', { exact: true }).waitFor(); await page.locator('.settings-nav').waitFor();
  await page.getByRole('button', { name: 'Siguiente', exact: true }).click(); await page.getByText('Paso 4 de 5', { exact: true }).waitFor(); await page.getByRole('button', { name: 'Iniciar grabación', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Siguiente', exact: true }).click(); await page.getByText('Paso 5 de 5', { exact: true }).waitFor(); await page.locator('.page-heading').waitFor();
  await page.getByRole('button', { name: 'Listo', exact: true }).click();
  await page.getByRole('button', { name: 'Iniciar grabación', exact: true }).waitFor();
  assert.equal(await page.getByRole('button', { name: 'Volver', exact: true }).count(), 0);
  console.log('PASS finishing the tutorial returns to the home recorder');
  await page.getByRole('button', { name: 'Ayuda', exact: true }).click();
  await page.getByRole('heading', { name: '¿Qué necesitas hacer?' }).waitFor();
  await page.getByText('Abre “Qué quieres grabar” y elige pantalla, ventana o área.', { exact: true }).waitFor();
  await page.getByRole('button', { name: /Conseguir una voz clara/ }).click();
  await page.getByText('Habla con tu volumen normal y mantén el medidor en la zona verde.', { exact: true }).waitFor();
  await page.getByRole('button', { name: /Usar el teleprompter/ }).click();
  await page.getByText('Repite el recorrido breve de cinco pasos.', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Abrir ajustes de guion', exact: true }).click();
  await page.getByRole('button', { name: 'Guion', exact: true }).waitFor();
  await page.screenshot({ path: path.join(output, 'help-guides.png') });
  console.log('PASS tutorial exposes a real spotlight and Help contains usable, synchronized guides');

  assert.equal(await page.getByLabel('Velocidad del teleprompter', { exact: true }).locator('option').count(), 5);
  const teleprompterScript = `Energía: $E=mc^2$\n\n$$\\frac{-b \\pm \\sqrt{b^2-4ac}}{2a}$$\n\n${Array.from({ length: 40 }, (_, index) => `Texto de prueba para el teleprompter protegido, línea ${index + 1}.`).join(' ')}`;
  await page.getByLabel('Texto del teleprompter', { exact: true }).fill(teleprompterScript);
  const promptOpening = app.waitForEvent('window');
  await page.getByRole('button', { name: 'Abrir teleprompter', exact: true }).click();
  const prompt = await promptOpening;
  await prompt.getByText('Texto de prueba para el teleprompter protegido, línea 1.', { exact: false }).waitFor();
  assert.equal(await prompt.locator('.katex').count(), 2);
  assert.equal(await prompt.locator('.katex-display').count(), 1);
  assert.equal((await page.evaluate(() => window.desktop.config())).settings.teleprompterText, teleprompterScript);
  const protectedWindow = await app.evaluate(({ BrowserWindow }) => {
    const window = BrowserWindow.getAllWindows().find(item => item.getTitle() === 'Tomixel Teleprompter');
    return window ? { width: window.getSize()[0], visible: window.isVisible() } : null;
  });
  assert.deepEqual(protectedWindow, { width: 620, visible: true });
  const scrollBefore = await prompt.locator('.teleprompter-content').evaluate(element => element.scrollTop);
  await prompt.getByRole('button', { name: 'Leer', exact: true }).click(); await prompt.waitForTimeout(800);
  const scrollAfter = await prompt.locator('.teleprompter-content').evaluate(element => element.scrollTop);
  assert.ok(scrollAfter > scrollBefore); await prompt.getByRole('button', { name: 'Pausar', exact: true }).click();
  await prompt.keyboard.press('Space');
  await prompt.getByRole('button', { name: 'Pausar', exact: true }).waitFor();
  await prompt.keyboard.press('ArrowUp');
  await prompt.getByText('Rápido · 160 ppm', { exact: true }).waitFor();
  console.log('PASS teleprompter saves editable text, renders formulas and responds to keyboard controls');
  await prompt.keyboard.press('Control+w');
  await prompt.waitForTimeout(100);
  assert.equal(await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().find(window => window.getTitle() === 'Tomixel Teleprompter')?.isVisible()), true);
  const teleprompterContent = prompt.locator('.teleprompter-content');
  await teleprompterContent.evaluate(element => { element.style.paddingBottom = '1000px'; element.scrollTop = 118; element.dispatchEvent(new Event('scroll')); });
  await page.getByRole('button', { name: 'Abrir teleprompter', exact: true }).click();
  await prompt.waitForTimeout(100);
  assert.equal(await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().find(window => window.getTitle() === 'Tomixel Teleprompter')?.isVisible()), false);
  await page.getByRole('button', { name: 'Abrir teleprompter', exact: true }).click();
  await prompt.waitForTimeout(100);
  assert.equal(await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().find(window => window.getTitle() === 'Tomixel Teleprompter')?.isVisible()), true);
  assert.ok(await teleprompterContent.evaluate(element => element.scrollTop >= 100));
  console.log('PASS teleprompter toggle preserves its reading position');
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().find(window => window.getTitle() === 'Tomixel Teleprompter')?.destroy());
} finally {
  await app?.close();
}
